"""Adapt shared Tilemo sources to ArkTS syntax."""
from pathlib import Path

app = Path(__file__).resolve().parent
repo = app.parents[1]
target = app / 'entry/src/main/ets/model'
for package, files in [('data', ['types', 'defaults']), ('core', ['metro', 'quotes', 'time'])]:
    for name in files:
        source = (repo / 'packages' / package / 'src' / (name + '.ts')).read_text()
        source = source.replace('import type ', 'import ').replace('"@tilemo/data"', '"./types"')
        source = source.replace('  [k: string]: unknown;\n', '')
        source = source.replace('ReturnType<typeof setInterval>', 'number').replace('ReturnType<typeof setTimeout>', 'number')
        source = source.replace('plan: {\n  contract: number;\n  relax: number;\n  reps: number;\n  sets: number;\n}', 'plan: Plan')
        if name == 'time':
            source = 'import { Plan } from "./types";\n' + source
        source = source.replace('  private pause(): void', '  pause(): void')
        (target / (name + '.ets')).write_text('// Generated by sync-core.py.\n' + source)
